UPDATE public.tax_types
SET name = 'Общий налоговый режим'
WHERE name = 'Общий режим'
  AND NOT EXISTS (
      SELECT 1 FROM public.tax_types existing
      WHERE existing.name = 'Общий налоговый режим'
  );

UPDATE public.tax_types
SET name = 'Упрощенная система налогообложения на основе единого налога'
WHERE name = 'Единый налог'
  AND NOT EXISTS (
      SELECT 1 FROM public.tax_types existing
      WHERE existing.name = 'Упрощенная система налогообложения на основе единого налога'
  );

UPDATE public.tax_types
SET name = 'Налог на основе патента'
WHERE name = 'Патентная система / Специальный режим'
  AND NOT EXISTS (
      SELECT 1 FROM public.tax_types existing
      WHERE existing.name = 'Налог на основе патента'
  );

